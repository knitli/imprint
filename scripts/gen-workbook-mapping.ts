// Write docs/workbook-mapping.md from the mapping table in src/export/xlsx.ts,
// so the published mapping can never drift from the code.
// Usage: node scripts/gen-workbook-mapping.ts [--check]
import { readFile, writeFile } from "node:fs/promises";
import { ABOUT_FIELDS, LIMITATIONS, MAPPING_VERSION, NOT_MAPPED, SHEETS } from "../src/export/xlsx.ts";

const path = new URL("../docs/workbook-mapping.md", import.meta.url);
const lines = [
  "# Workbook mapping",
  "",
  `<!-- Generated by scripts/gen-workbook-mapping.ts. Do not edit by hand. -->`,
  "",
  `Mapping version: \`${MAPPING_VERSION}\`. Decision [0006](decisions/0006-exceljs-for-workbooks.md).`,
  "",
  `> ${LIMITATIONS}`,
  "",
  "Every value is written as a plain text cell, never as a formula or an Excel date. Rows 1 to 3 of every sheet repeat the guide's banner, its status label and its identity (guide ID, revision and payload digest).",
  "",
  "## Sheet: About",
  "",
  "| Field | JSON pointer | Encoding |",
  "| --- | --- | --- |",
  ...ABOUT_FIELDS.map(([label, ptr, enc = "text"]) => `| ${label} | \`${ptr}\` | ${enc} |`),
  "",
];
for (const sh of SHEETS) {
  lines.push(
    `## Sheet: ${sh.name}`,
    "",
    sh.title,
    "",
    "| Column | JSON pointer (relative to the row's item) | Encoding |",
    "| --- | --- | --- |",
  );
  for (const c of sh.columns)
    lines.push(
      `| ${c.h} | ${c.display ? "(display only, not read back)" : `\`${c.p}\``} | ${c.display ? "" : (c.t ?? "text")} |`,
    );
  lines.push("");
}
lines.push("## Not carried in the workbook", "", "| JSON pointer | Why |", "| --- | --- |");
for (const [p, why] of Object.entries(NOT_MAPPED)) lines.push(`| \`${p}\` | ${why} |`);
lines.push(
  "",
  "Each workbook's About sheet lists the specific items it does not carry (its loss report).",
  "",
);
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(path, "utf8").catch(() => "");
  if (current !== text) {
    console.error("docs/workbook-mapping.md is out of date. Run: node scripts/gen-workbook-mapping.ts");
    process.exit(1);
  }
} else {
  await writeFile(path, text);
}

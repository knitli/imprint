// Writes MAPPING.md from the same table mapping.mjs uses, so the document cannot drift from the code.
import { writeFileSync } from "node:fs";
import { ABOUT_FIELDS, LIMITATIONS, MAPPING_VERSION, NOT_MAPPED, SHEETS } from "./mapping.mjs";

const md = (s) => String(s).replace(/\|/g, "\\|");
const L = [];
L.push(`# Workbook mapping \`${MAPPING_VERSION}\``, "");
L.push("**Status:** spike output (SP-05). Generated by `gen-mapping.mjs` from `mapping.mjs`. Synthetic data only.", "");
L.push("This is the documented mapping OpenSCG spec §10.4 asks for. OpenSCG 0.1 defines no workbook layout, so this one is ours. It is **not** a DoD or DTIC layout.", "");
L.push("## Statement printed in every workbook", "", `> ${LIMITATIONS}`, "");
L.push("## Rules that apply to every sheet", "");
L.push(
  "- **Rows 1–3 of every sheet** repeat the document banner (`document_markings.banner`), the labels `SYNTHETIC` (when `synthetic` is true) and `DRAFT / NOT APPROVED` (unless the revision has a technically valid attestation), and the guide ID, revision ID and payload digest (spec §10.1).",
  "- **Print header and footer** repeat the banner, centred, on every printed page. The footer also carries the labels and page numbers.",
  "- **Row 6 is the header row.** It is frozen and has a filter. Data starts on row 7.",
  "- **Every value is a text cell.** No formulas, no Excel dates, no numbers. Dates stay as `YYYY-MM-DD` text, so no time-zone shift. Cells use the Text number format (`@`) so they stay text if someone edits them.",
  "- **Formula injection.** Text that starts with `=`, `+`, `-`, `@`, tab or CR is stored as a shared string (`t=\"s\"`), never as a formula (spec §10.4). It is not altered (no leading apostrophe), so the round trip is exact.",
  "- **Characters XML cannot hold** (CR, other control characters) and literal `_xHHHH_` sequences are escaped the OOXML way (`_x000D_`, `_x005F_`). Excel and LibreOffice decode these.",
  "- **Lists** (references, §1.4 categories, document controls) put one item per line in one cell.",
  "- **Display-only columns** are written for people (for example \"Level: U to C (see conditions)\") and ignored when the workbook is read back.",
  "- **Bytes are deterministic** for a given guide and export time: every zip entry gets the same timestamp.",
  "",
);
L.push("## Sheet `About` (one row per field)", "", "Columns: Field, Value, JSON pointer. The first rows are computed: payload digest algorithm and value, OpenSCG version, mapping version, and **Not carried in this workbook** (extensions and attestations that the mapping leaves out).", "");
L.push("| Field label | JSON pointer | Encoding |", "| --- | --- | --- |");
for (const [label, p, t = "text"] of ABOUT_FIELDS) L.push(`| ${md(label)} | \`${p}\` | ${t} |`);
L.push("");
for (const sh of SHEETS) {
  L.push(`## Sheet \`${sh.name}\``, "", `${sh.title}.`, "");
  L.push("| Column | JSON pointer (relative to the row's item) | Encoding |", "| --- | --- | --- |");
  for (const c of sh.columns) {
    const p = c.display ? "(display-only)" : c.p.startsWith("#") ? `${c.p} (row bookkeeping)` : `\`${c.p}\``;
    L.push(`| ${md(c.h)} | ${p} | ${c.display ? "" : (c.t ?? "text")} |`);
  }
  L.push("");
}
L.push(
  "Row bookkeeping columns: `#order` is the entry's position in `/entries` (elements and compilations are on separate sheets, so this keeps the original order); `#entry` links a control or source to its entry; `#rel` says which list a Links row came from (`supersedes`, `superseded_by`, `previous_revision`, `event`, `review_evidence`).",
  "",
);
L.push("## Sheet `Mapping`", "", "The workbook repeats this table, so a reader holding only the workbook can see where each column comes from.", "");
L.push("## Deliberately not carried", "", "| Pointer | Why |", "| --- | --- |");
for (const [p, why] of Object.entries(NOT_MAPPED)) L.push(`| \`${p}\` | ${md(why)} |`);
L.push("", "Everything else in the OpenSCG 0.1 schema is carried. `out/coverage.md` proves that field by field with a round trip.", "");
writeFileSync("MAPPING.md", L.join("\n"));
console.log("wrote MAPPING.md");
